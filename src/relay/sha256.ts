/**
 * SHA-256 and HMAC-SHA256 in plain JavaScript (FIPS 180-4, RFC 2104).
 *
 * The plugin's JavaScript engine has no WebCrypto, and the relay protocol
 * only needs these two functions on short inputs, so a compact
 * implementation is enough.
 */

/* eslint-disable no-bitwise -- the algorithm is defined on 32-bit words. */

